def text_to_lines(text):
    lines = []
    for c in text:
        letter = FONT.get(c, FONT[" "])
        lines += letter
        lines += [0x00]
    return lines

def text_to_lines_small(text, offset=1):
    lines = []
    for c in text.upper():
        letter = FONT_SMALL.get(c, FONT_SMALL[" "])
        lines += [col << offset for col in letter]
        lines += [0x00]
    return lines
